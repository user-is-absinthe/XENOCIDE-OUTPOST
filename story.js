  const milestones = entries.map(e => e.depth);

  const at = depth => entries.find(e => e.depth === Number(depth)) || null;

  /* Вставка, которую ещё не показывали на этой глубине, или null. */
  function pending(S, depth) {
    const entry = at(depth);
    if (!entry) return null;
    const seen = Array.isArray(S && S.seenStory) ? S.seenStory : [];
    return seen.includes(entry.id) ? null : entry;
  }

  function mark(S, id) {
    if (!S) return;
    if (!Array.isArray(S.seenStory)) S.seenStory = [];
    if (!S.seenStory.includes(id)) S.seenStory.push(id);
  }

  return { entries, milestones, at, pending, mark };
